"""Producer for paper/tables/t4_01_cams_baseline_variants.csv (Section 4.4).

WHY THIS FILE EXISTS
--------------------
`t4_01_cams_baseline_variants.csv` was committed in 99b9a13 ("Phase 7: consolidate tables")
as a NEW file, copied from the untracked `results/tables/` directory that the same commit
deleted. Its producer was never committed, so from that point the table could not be
regenerated by anything in the repository -- `paper/scripts/extract_numbers.py:102` reads it
and nothing writes it.

This script reconstructs it from the same inputs and the same library functions the rest of
the pipeline uses (`ecopulse_ca.models.cams_baseline`). It is a RECONSTRUCTION, not the
original code, which is lost. Whether the reconstruction is faithful is decided by comparing
its output against the banked file -- see `--check`, and the provenance note in
review/DEFECT_REGISTER.md. Nothing here is tuned to make the numbers match.

Evaluation set: the frozen 2024 test block, per station, joining daily observed PM2.5 to the
CAMS forecast. This is deliberately NOT inner-joined against the model feature table, which
is why the row counts here exceed those in t6_01 -- the CAMS baseline needs no model features.
"""

from __future__ import annotations

import argparse
import json
import pathlib
import sys

import pandas as pd

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from ecopulse_ca.eval.metrics import regression_metrics
from ecopulse_ca.models.cams_baseline import apply_local_debias, apply_pooled_debias, fit_bias
from ecopulse_ca.models.feature_table import daily_target

OUT = ROOT / "paper" / "tables" / "t4_01_cams_baseline_variants.csv"


def build() -> pd.DataFrame:
    splits = json.loads((ROOT / "benchmark" / "splits" / "splits.json").read_text())
    blocks = {b["name"]: b for b in splits["temporal_blocks"]}
    tr_end = pd.Timestamp(blocks["train"]["end"]).tz_localize(None)
    te_lo = pd.Timestamp(blocks["test"]["start"]).tz_localize(None)
    te_hi = pd.Timestamp(blocks["test"]["end"]).tz_localize(None)

    city_of = {str(s["station_id"]): s["city"] for s in splits["stations"]}

    panel = pd.read_parquet(ROOT / "data/interim/benchmark_panel.parquet")
    panel.columns = [str(c) for c in panel.columns]
    tg = daily_target(panel, city_of)
    observed = {sid: g.set_index(g.date.dt.date).pm25 for sid, g in tg.groupby("station_id")}

    cams = pd.read_parquet(ROOT / "data/interim/cams_pm25_forecast.parquet")
    cams["station_id"] = cams.station_id.astype(str)
    cams["date"] = pd.to_datetime(cams.time).dt.normalize()

    bias = fit_bias(cams, observed, tr_end)

    rows = []
    for sid, city in city_of.items():
        obs = observed.get(sid)
        if obs is None:
            continue
        sub = cams[cams.station_id == sid].copy()
        if sub.empty:
            continue
        sub = sub[(sub.date >= te_lo) & (sub.date <= te_hi)]
        j = sub.assign(d=sub.date.dt.date).set_index("d").join(
            pd.DataFrame({"obs": obs}), how="inner"
        )
        j = j.dropna(subset=["obs", "cams_pm25_forecast"])
        if j.empty:
            continue

        # held_out for the pooled variant is this station's whole city: under leave-city-out
        # no station in the held-out city may inform its own correction.
        held = {s for s, c in city_of.items() if c == city}

        variants = {
            "raw": j["cams_pm25_forecast"],
            "debiased_local": apply_local_debias(j, bias),
            "debiased_pooled": apply_pooled_debias(j, bias, held_out=held),
        }
        for name, pred in variants.items():
            m = regression_metrics(j["obs"], pd.Series(pred, index=j.index))
            rows.append({"city": city, "station": sid, "variant": name, **m.as_dict()})

    # Emit the banked schema exactly -- column set AND order. `regression_metrics.as_dict()`
    # also carries `median_ae`, which the original table did not, and downstream consumers
    # (paper/scripts/extract_numbers.py, tests/test_manuscript_numbers.py) read this file by
    # name. A schema change here is a silent break there.
    return pd.DataFrame(rows)[["city", "station", "variant", "rmse", "mae", "bias", "r2", "n"]]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument(
        "--check",
        action="store_true",
        help="compare against the banked file instead of overwriting it",
    )
    args = ap.parse_args()

    df = build()

    if args.check:
        if not OUT.exists():
            print(f"FAIL: {OUT} missing")
            return 1
        old = pd.read_csv(OUT, dtype={"station": str})
        new = df.astype({"station": str})
        key = ["city", "station", "variant"]
        merged = old.merge(new, on=key, suffixes=("_old", "_new"), how="outer", indicator=True)
        unmatched = merged[merged._merge != "both"]
        print(f"rows: banked={len(old)} rebuilt={len(new)} matched={(merged._merge=='both').sum()}")
        if len(unmatched):
            print(f"UNMATCHED KEYS: {len(unmatched)}")
            print(unmatched[key + ["_merge"]].to_string(index=False))
        both = merged[merged._merge == "both"]
        worst = 0.0
        for col in ("rmse", "mae", "bias", "r2", "n"):
            if f"{col}_old" in both:
                d = (both[f"{col}_old"] - both[f"{col}_new"]).abs().max()
                print(f"  {col:<6} max|delta| = {d:.6g}")
                worst = max(worst, float(d))
        print(f"\n=> {'REPRODUCES' if worst < 1e-9 and not len(unmatched) else 'DOES NOT REPRODUCE'}")
        return 0 if (worst < 1e-9 and not len(unmatched)) else 1

    df.to_csv(OUT, index=False)
    print(f"wrote {OUT} ({len(df)} rows)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
