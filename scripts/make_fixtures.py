PM25_SENSOR = {"id": 0, "name": "pm25 ug/m3", "parameter": {
    "id": 2, "name": "pm25", "units": "ug/m3", "displayName": "PM2.5"}}


def sensor(sid: int) -> dict:
    s = json.loads(json.dumps(PM25_SENSOR))
    s["id"] = sid
    return s


def location(
    *, lid: int, name: str, locality: str, iso: str, country: str, lat: float, lon: float,
    tz: str, first: str, last: str, sensors: list[int], is_monitor: bool = False,
    is_mobile: bool = False, provider: str = "Unknown",
) -> dict:
    return {
        "id": lid,
        "name": name,
        "locality": locality,
        "timezone": tz,
        "country": {"id": 1, "code": iso, "name": country},
        "owner": {"id": 1, "name": "Unknown"},
        "provider": {"id": 1, "name": provider},
        "isMobile": is_mobile,
        "isMonitor": is_monitor,
        "instruments": [{"id": 2, "name": "Reference monitor" if is_monitor else "Low-cost sensor"}],
        "sensors": [sensor(s) for s in sensors],
        "coordinates": {"latitude": lat, "longitude": lon},
        "licenses": [{"attribution": {"name": provider}, "dateFrom": first, "dateTo": None}],
        "bounds": [lon - 0.01, lat - 0.01, lon + 0.01, lat + 0.01],
        "distance": None,
        "datetimeFirst": {"utc": f"{first}T00:00:00Z", "local": f"{first}T05:00:00+05:00"},
        "datetimeLast": {"utc": f"{last}T00:00:00Z", "local": f"{last}T05:00:00+05:00"},
    }


