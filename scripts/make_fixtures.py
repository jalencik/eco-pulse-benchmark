def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    for iso, locs in FIXTURES.items():
        payload = {
            "meta": {"name": "openaq-api", "website": "/", "page": 1,
                     "limit": 1000, "found": len(locs)},
            "results": locs,
        }
        path = OUT / f"openaq_locations_{iso}.json"
        path.write_text(json.dumps(payload, indent=2, ensure_ascii=False), encoding="utf-8")
        print(f"wrote {path.name}  ({len(locs)} locations)")


if __name__ == "__main__":
    main()
