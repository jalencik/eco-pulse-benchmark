"""Render research/sources.json into the markdown block embedded in LITERATURE.md.

Run:  python scripts/build_literature_table.py

Same principle as the results tables: a citation that is typed by hand is a citation that
can drift from its source. The reference list is generated from the resolved records, so
authors, years and DOIs in the review cannot disagree with what the APIs actually returned.

Writes research/SOURCES_TABLE.md, which LITERATURE.md includes by reference.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "research" / "sources.json"
OUT = ROOT / "research" / "SOURCES_TABLE.md"

# Depth is what was retrieved. Bibliographic verification is a separate axis: a record can
# have an authoritative DOI and author list from Crossref while its full text stays behind
# a paywall. Conflating the two is what let a "SNIPPET" source look uncitable when in fact
# only its *content claims* were provisional, not its identity.
DEPTH_ORDER = {"FULL": 0, "ABSTRACT": 1, "SNIPPET": 2, "UNRESOLVED": 3}


def fmt_authors(authors: list[str] | None) -> str:
    if not authors:
        return "—"
    if len(authors) == 1:
        return authors[0]
    if len(authors) <= 3:
        return ", ".join(authors)
    return f"{authors[0]} et al."


def main() -> int:
    if not SRC.exists():
        print(f"missing {SRC}; run scripts/fetch_literature.py first", file=sys.stderr)
        return 1
    records = json.loads(SRC.read_text(encoding="utf-8"))
    records.sort(key=lambda r: (DEPTH_ORDER.get(r["depth"], 9), r["ref"]))

    lines = [
        "<!-- GENERATED by scripts/build_literature_table.py -- do not edit by hand -->",
        "",
        "| Ref | Depth | Citation verified | First author | Year | Venue | DOI |",
        "|---|---|---|---|---|---|---|",
    ]
    counts: dict[str, int] = {}
    for r in records:
        counts[r["depth"]] = counts.get(r["depth"], 0) + 1
        if r["depth"] == "UNRESOLVED":
            lines.append(
                f"| {r['ref']} | UNRESOLVED | no | — | — | "
                f"*not indexed; closest rejected: {str(r.get('closest_rejected'))[:48]}* | — |"
            )
            continue
        doi = r.get("doi")
        lines.append(
            f"| {r['ref']} | {r['depth']} | "
            f"{'yes' if doi else 'partial'} | "
            f"{fmt_authors(r.get('authors'))} | {r.get('year') or '—'} | "
            f"{r.get('venue') or '—'} | "
            f"{f'`{doi}`' if doi else '—'} |"
        )

    total = len(records)
    usable = sum(v for k, v in counts.items() if k in ("FULL", "ABSTRACT"))
    with_doi = sum(1 for r in records if r.get("doi"))
    lines += [
        "",
        f"**{total} records resolved via API.** "
        + ", ".join(f"{k}={v}" for k, v in sorted(counts.items()))
        + f". {with_doi} carry an authoritative DOI; {usable} reached abstract depth or better.",
    ]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT}  ({total} records)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
