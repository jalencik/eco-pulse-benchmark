"""Assemble the rendered sections into one manuscript, with a generated reference list.

Run:  python paper/scripts/stitch.py

Reads paper/sections/*.md (the *rendered* output, never the templates) and writes
paper/extended_technical_report.md.

Two refusals are deliberate:

1. **It will not stitch a template.** If a `.md.tmpl` is newer than its rendered `.md`, the
   rendered file is stale and the manuscript would carry last run's numbers. Stitching is
   the last step that can catch that, so it fails rather than producing a plausible file.

2. **It will not emit an unresolved placeholder.** `render.py` already treats those as
   fatal, but the stitched artifact is what a reader receives, so the check is repeated on
   the final bytes. A `{{taskn_cams_rmse}}` reaching a PDF is worse than a failed build.

The reference list is built from research/sources.json — the same records the resolver
verified — rather than typed. Hand-typed citations drift from their sources exactly as
hand-typed numbers do, and a wrong DOI is the one error a reviewer can confirm in seconds.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SEC = ROOT / "paper" / "sections"
SOURCES = ROOT / "research" / "sources.json"
OUT = ROOT / "paper" / "extended_technical_report.md"

PLACEHOLDER = re.compile(r"\{\{([a-zA-Z0-9_]+)\}\}")

TITLE = "A Station-Level Air Quality Benchmark for Central Asia"
SUBTITLE = (
    "Frozen leave-city-out splits, an operational-availability account, "
    "and an honestly-evaluated transfer baseline"
)

# Cited in the text but not indexed by any of the four scholarly APIs. Recorded explicitly
# so the reference list is complete and the provenance of each entry stays visible: these
# two are grey literature (a policy report and a Zenodo deposit), not journal articles.
UNINDEXED: dict[str, dict[str, str]] = {
    "A1": {
        "authors": "OpenAQ",
        "year": "2025",
        "title": "Air Quality Data: Central Asia — regional snapshot of the 2024 Global "
        "Air Quality Data Landscape report",
        "venue": "OpenAQ (policy report)",
        "note": "read in full; not a journal article, so absent from Crossref/OpenAlex",
    },
    "A3": {
        "authors": "Guttikunda, S.",
        "year": "2024",
        "title": "A multi-pollutant emissions inventory and air quality analysis for Bishkek",
        "venue": "Zenodo 12720883 (CC-BY)",
        "note": "read in full; Zenodo deposit, not indexed by the APIs used here",
    },
}


def check_freshness() -> list[str]:
    """A rendered section older than its template is stale, and silently so."""
    stale = []
    for tmpl in sorted(SEC.glob("*.md.tmpl")):
        rendered = SEC / tmpl.name.replace(".md.tmpl", ".md")
        if not rendered.exists():
            stale.append(f"{rendered.name} (never rendered)")
        elif rendered.stat().st_mtime < tmpl.stat().st_mtime:
            stale.append(f"{rendered.name} (older than its template)")
    return stale


def author_sort_key(rec: dict) -> tuple:
    authors = rec.get("authors") or []
    surname = authors[0].split()[-1].lower() if authors else "zzz"
    return (surname, rec.get("year") or 0)


def format_reference(rec: dict) -> str:
    authors = rec.get("authors") or []
    if not authors:
        who = "—"
    elif len(authors) == 1:
        who = authors[0]
    elif len(authors) <= 3:
        who = ", ".join(authors[:-1]) + f" and {authors[-1]}"
    else:
        who = f"{authors[0]} et al."
    parts = [f"{who} ({rec.get('year') or 'n.d.'}). *{rec.get('title')}*."]
    if rec.get("venue"):
        parts.append(f"{rec['venue']}.")
    if rec.get("doi"):
        parts.append(f"https://doi.org/{rec['doi']}")
    return " ".join(parts)


def build_references() -> list[str]:
    lines = [
        "## References",
        "",
        "Generated by `paper/scripts/stitch.py` from `research/sources.json`. Every entry "
        "was resolved through OpenAlex, Crossref, Semantic Scholar or Europe PMC and "
        "checked against a title-match gate; none is typed by hand.",
        "",
    ]
    records = json.loads(SOURCES.read_text(encoding="utf-8"))
    resolved = [r for r in records if r["depth"] != "UNRESOLVED" and r.get("title")]
    for rec in sorted(resolved, key=author_sort_key):
        lines.append(f"- **[{rec['ref']}]** {format_reference(rec)}")

    lines += ["", "### Sources not indexed by the resolvers", ""]
    for ref, rec in UNINDEXED.items():
        lines.append(
            f"- **[{ref}]** {rec['authors']} ({rec['year']}). *{rec['title']}*. "
            f"{rec['venue']}. — {rec['note']}"
        )

    # A ref recorded in UNINDEXED was read in full and is simply absent from the APIs.
    # Listing it again as "not obtained" would contradict the entry directly above it.
    unresolved = [r for r in records if r["depth"] == "UNRESOLVED" and r["ref"] not in UNINDEXED]
    if unresolved:
        lines += [
            "",
            "### Sought but not obtained",
            "",
            "Listed so the gap is visible rather than absent. No claim in this manuscript "
            "rests on these.",
            "",
        ]
        for r in unresolved:
            lines.append(f"- **[{r['ref']}]** query: *{r['query']}* — no matching record.")
    return lines


def main() -> int:
    stale = check_freshness()
    if stale:
        print("REFUSING to stitch stale sections:", file=sys.stderr)
        for s in stale:
            print(f"  {s}", file=sys.stderr)
        print("\nrun: python paper/scripts/render.py", file=sys.stderr)
        return 1

    sections = sorted(SEC.glob("*.md"))
    sections = [p for p in sections if not p.name.endswith(".md.tmpl")]
    if not sections:
        print("no rendered sections found", file=sys.stderr)
        return 1

    # The title block lives in 00_abstract.md.tmpl, which sorts first. Emitting TITLE here
    # too would print the paper's name twice on page one.
    #
    # The reproduction banner is appended AFTER the first section rather than before it. It
    # used to be the first block in the document, which put an unexplained build-system note
    # above the paper's own title on page one of the PDF -- the first thing a reader saw.
    REPRO_BANNER = (
        "> **Reproduction.** Every figure below is regenerated by `make reproduce` "
        "(or `python tasks.py reproduce`) from the frozen splits in "
        "`benchmark/splits/splits.json`, checksum "
        "`544a044c…f9e0c6c`. No number in this document is typed by hand."
    )
    body: list[str] = []
    for i, path in enumerate(sections):
        body.append(path.read_text(encoding="utf-8").rstrip())
        body.append("")
        if i == 0:  # after the title/abstract block, before the body sections
            body += [REPRO_BANNER, ""]
        body.append("---")
        body.append("")

    body += build_references()
    text = "\n".join(body) + "\n"

    leftover = sorted(set(PLACEHOLDER.findall(text)))
    if leftover:
        print(
            f"REFUSING: unresolved placeholders in the stitched output: {leftover}", file=sys.stderr
        )
        return 1

    OUT.write_text(text, encoding="utf-8")
    words = len(text.split())
    print(f"wrote {OUT}")
    print(f"  {len(sections)} sections, {words:,} words, {len(text):,} characters")
    for p in sections:
        print(f"    {p.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
